class MomentGenerator:
    """朋友圈文案生成器"""
    
    def __init__(self):
        self.scenes = list(SCENE_TEMPLATES.keys())
        self.styles = ["literary", "humor", "cold", "warm", "vaush", "poet"]
        self.style_names = {
            "literary": "文艺清新",
            "humor": "搞笑幽默", 
            "cold": "高冷简约",
            "warm": "温暖治愈",
            "vaush": "凡尔赛",
            "poet": "朋友圈诗人"
        }
    
    def generate(
        self, 
        scene: str, 
        style: str, 
        custom_keyword: str = "",
        count: int = 3
    ) -> List[MomentResult]:
        """
        生成朋友圈文案
        
        Args:
            scene: 场景类型 (food/travel/fitness/pet/work/party/daily/love)
            style: 风格类型 (literary/humor/cold/warm/vaush/poet)
            custom_keyword: 自定义关键词
            count: 生成数量
            
        Returns:
            List[MomentResult] 生成结果列表
        """
        if scene not in self.scenes:
            scene = random.choice(self.scenes)
        if style not in self.styles:
            style = random.choice(self.styles)
            
        scene_data = SCENE_TEMPLATES[scene]
        templates = scene_data["styles"].get(style, scene_data["styles"]["literary"])
        
        results = []
        used_templates = []
        
        for _ in range(count):
            # 避免重复选择相同的模板
            available = [t for t in templates if t not in used_templates]
            if not available:
                available = templates
                
            template = random.choice(available)
            used_templates.append(template)
            
            # 替换关键词
            keyword = custom_keyword if custom_keyword else random.choice(scene_data["keywords"])
            content = template.replace("{keyword}", keyword)
            
            # 随机选择emoji组合
            emoji_combo = random.choice(EMOJI_COMBOS.get(scene, [["✨"]] * 5))
            emojis = emoji_combo[:3]  # 取前3个
            
            # 随机选择自嘲回复
            self_deprecating = random.choice(SELF_DEPRECATING_REPLIES)
            
            # 随机选择定位文案
            location = random.choice(LOCATION_TEXTS.get(scene, ["朋友圈"]))
            
            # 配图建议
            tips = f"建议搭配{len(emoji_combo)}个{emojis[0]}类emoji，或者用实拍图+滤镜更自然"
            
            results.append(MomentResult(
                content=content,
                emojis=emojis,
                self_deprecating_reply=self_deprecating,
                location_text=location,
                tips=tips
            ))
        
        return results
    
    def get_scenes(self) -> List[Dict]:
        """获取所有场景列表"""
        return [
            {"id": key, "name": data["name"], "keywords": data["keywords"]}
            for key, data in SCENE_TEMPLATES.items()
        ]
    
    def get_styles(self) -> List[Dict]:
        """获取所有风格列表"""
        return [
            {"id": key, "name": value}
            for key, value in self.style_names.items()
        ]


